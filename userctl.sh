#!/usr/bin/env bash
# =============================================================================
# userctl.sh — user & API-key management for LLM Portal
#
#   userctl.sh add <name>        create user with a fresh unique key
#   userctl.sh remove <name>     delete user + key
#   userctl.sh revoke <name>     replace user's key with a new one (old dies)
#   userctl.sh disable <name>    block access, keep the key for later
#   userctl.sh enable <name>     restore access after disable
#   userctl.sh list              list users (keys masked)
#   userctl.sh show <name>       print one user's full key (to copy to them)
#
# Configuration (env vars, with defaults):
#   KEY_FILE    path to API keys file    (default: ./data/api_keys.txt)
#   USERS_MD    path to users markdown   (default: ./data/users.md)
#   SVC         systemd service to restart on key change (default: llm-backend)
#   PORT        health-check port        (default: 8080)
#   LOGEVENT    event logging script     (default: ./log-event.sh)
#   WAIT_HEALTHY=1  wait for backend health after restart (default: 1)
#
# Examples:
#   ./userctl.sh add carol
#   ./userctl.sh show alice
#   ./userctl.sh disable bob
# =============================================================================
set -euo pipefail

PROJ="${PROJ:-$(cd "$(dirname "$0")" && pwd)}"
KEYFILE="${KEY_FILE:-$PROJ/data/api_keys.txt}"
USERSMD="${USERS_MD:-$PROJ/data/users.md}"
SVC="${SVC:-llm-backend}"
PORT="${PORT:-8080}"
LOGEVENT="${LOGEVENT:-$PROJ/log-event.sh}"

ev() { [[ -x "$LOGEVENT" ]] && "$LOGEVENT" "aiuser $1 user=$2" ; }

[[ -f "$KEYFILE" ]] || { echo "error: $KEYFILE missing" >&2; exit 1; }

validate_name() {
  [[ "$1" =~ ^[a-z][a-z0-9_-]{0,30}$ ]] || {
    echo "error: invalid username '$1' (allowed: a-z 0-9 - _ , starts with a letter)" >&2; exit 1; }
}

wait_healthy() {
  systemctl restart "$SVC"
  for _ in $(seq 1 45); do
    sleep 2
    curl -sf -m 2 "http://127.0.0.1:${PORT}/health" >/dev/null 2>&1 && { echo "server restarted, healthy"; return 0; }
  done
  echo "warning: server not healthy yet — check: journalctl -u $SVC -n 30" >&2
}

# regenerates auth/users.md from the key file (single source of truth)
regen_usersmd() {
  python3 - "$KEYFILE" "$USERSMD" <<'PYEOF'
import sys
keyf, usersf = sys.argv[1], sys.argv[2]
entries = []          # (name, key, disabled)
lines = open(keyf).read().splitlines()
i = 0
while i < len(lines):
    l = lines[i].strip()
    if l.startswith("# user:"):
        name = l.split(":", 1)[1].strip()
        key = lines[i+1].strip() if i + 1 < len(lines) else ""
        disabled = key.startswith("# DISABLED")
        if disabled:
            key = key.replace("# DISABLED ", "", 1)
        entries.append((name, key, disabled))
        i += 2
        continue
    i += 1
with open(usersf, "w") as f:
    f.write("# User credentials (KEEP PRIVATE - admin only)\n")
    f.write("# auto-generated by userctl.sh - do not edit by hand\n\n")
    f.write("| User | API key | Status |\n|---|---|---|\n")
    for name, key, disabled in entries:
        status = "DISABLED" if disabled else "active"
        f.write(f"| {name} | `{key}` | {status} |\n")
PYEOF
}

key_line_no() { # absolute line number of user's key line
  awk -v n="$1" '
    /^# user:/ { cur = substr($0, 9); getline; if (cur == n) { print NR; exit } }
  ' "$KEYFILE"
}

cmd_add() {
  validate_name "$1"
  grep -q "^# user: $1\$" "$KEYFILE" && { echo "error: user '$1' already exists" >&2; exit 1; }
  local key="aisk-$1-$(openssl rand -hex 16)"
  { echo "# user: $1"; echo "$key"; } >> "$KEYFILE"
  chmod 600 "$KEYFILE"
  regen_usersmd
  echo "user '$1' created:"
  echo "  $key"
  ev "add" "$1"
  wait_healthy
}

cmd_remove() {
  validate_name "$1"
  local no
  no=$(key_line_no "$1") || true
  [[ -z "$no" ]] && { echo "error: user '$1' not found" >&2; exit 1; }
  sed -i "$((no-1))d;$no d" "$KEYFILE"   # drop the '# user:' line and the key line
  regen_usersmd
  echo "user '$1' removed (key revoked on the server)"
  ev "remove" "$1"
  wait_healthy
}

cmd_revoke() {
  validate_name "$1"
  local no newkey
  no=$(key_line_no "$1") || true
  [[ -z "$no" ]] && { echo "error: user '$1' not found" >&2; exit 1; }
  newkey="aisk-$1-$(openssl rand -hex 16)"
  sed -i "${no}s|.*|$newkey|" "$KEYFILE"
  regen_usersmd
  echo "user '$1' key rotated (old key no longer works):"
  echo "  $newkey"
  ev "revoke" "$1"
  wait_healthy
}

cmd_disable() {
  validate_name "$1"
  local no
  no=$(key_line_no "$1") || true
  [[ -z "$no" ]] && { echo "error: user '$1' not found" >&2; exit 1; }
  sed -i "${no}s/^/# DISABLED /" "$KEYFILE"
  regen_usersmd
  echo "user '$1' disabled (key kept)."
  ev "disable" "$1"
  wait_healthy
}

cmd_enable() {
  validate_name "$1"
  sed -i "/^# DISABLED aisk-$1-/s/^# DISABLED //" "$KEYFILE"
  regen_usersmd
  echo "user '$1' enabled."
  ev "enable" "$1"
  wait_healthy
}

cmd_list() {
  python3 - "$KEYFILE" <<'PYEOF'
import sys
lines = open(sys.argv[1]).read().splitlines()
i = 0
while i < len(lines):
    l = lines[i].strip()
    if l.startswith("# user:"):
        name = l.split(":", 1)[1].strip()
        key = lines[i+1].strip() if i + 1 < len(lines) else ""
        if key.startswith("# DISABLED"):
            print(f"{name:<10} DISABLED (key kept)")
        else:
            print(f"{name:<10} {key[:15]}...")
        i += 2
        continue
    i += 1
PYEOF
}

cmd_show() {
  local no key
  no=$(key_line_no "$1") || true
  [[ -z "$no" ]] && { echo "error: user '$1' not found" >&2; exit 1; }
  sed -n "${no}p" "$KEYFILE"
}

case "${1:-}" in
  add)     shift; cmd_add "$@" ;;
  remove)  shift; cmd_remove "$@" ;;
  revoke)  shift; cmd_revoke "$@" ;;
  disable) shift; cmd_disable "$@" ;;
  enable)  shift; cmd_enable "$@" ;;
  list)    cmd_list ;;
  show)    shift; validate_name "$1"; cmd_show "$1" ;;
  ""|-h|--help)
    grep '^#   ' "$0" | sed 's/^#   //'
    echo
    echo "examples:"
    echo "  $0 add carol        create user + key"
    echo "  $0 show alice       print alice's key to give to her"
    echo "  $0 disable bob      block bob (key kept)"
    echo "  $0 revoke alice     new key for alice (old one dies)"
    ;;
  *) echo "error: unknown command '$1' (try: add|remove|revoke|disable|enable|list|show)" >&2; exit 2 ;;
esac
